#!/usr/bin/env python3
"""Generate splat symbol files from Jet Force Gemini's runlink tables.

Jet Force Gemini loads most of its game code as relocatable "runlink"
modules. To link them at run time the ROM carries a global symbol table
(one word per symbol: module index << 20 | offset) and a parallel table of
name offsets into a string pool. This script reads those tables from the
user's own ROM and writes the names that belong to the main code segment
(module 0) as a splat symbol_addrs file. The output is ROM-derived and is
generated at extract time; it is not committed.

Usage: runlink_syms.py ROM OUT_SYMBOL_ADDRS [--modules OUT_MODULE_LIST]
"""
import argparse
import struct
import sys

# US 1.0 (NJFE) layout. These are the ROM addresses the runlink loader in
# main uses (see "ROM layout" in README.md).
LAYOUT = {
    "us": {
        "main_imports": 0x1ECF220,  # main's relocations against module symbols
        "symtab": 0x1ED0270,        # global symbol table
        "modtab": 0x1ED2780,        # module table, 0x20 bytes per module
        "modules": 0x1ED3B20,       # module images (text, data, relocations)
        "nameoffs": 0x1FEB040,      # name offsets, one word per symbol
        "names": 0x1FED550,         # name string pool
        # main (module 0) sections, filled in at run time by the loader
        "text": 0x80000450,
        "data": 0x800A0660,
        "bss": 0x800B0B50,
        "bss_end": 0x801059A0,
    }
}

SEC_RODATA, SEC_DATA, SEC_BSS = 4093, 4094, 4095


def u32(rom, off):
    return struct.unpack_from(">I", rom, off)[0]


def cstr(rom, off):
    end = rom.index(b"\0", off)
    return rom[off:end].decode("ascii")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("out")
    ap.add_argument("--version", default="us")
    ap.add_argument("--modules", help="also write a module list here")
    args = ap.parse_args()

    L = LAYOUT[args.version]
    rom = open(args.rom, "rb").read()
    nsyms = (L["modtab"] - L["symtab"]) // 4
    if (L["names"] - L["nameoffs"]) // 4 != nsyms:
        sys.exit("symbol and name tables disagree in length")

    seen_names = set()
    seen_addrs = {}
    lines = []
    for i in range(nsyms):
        v = u32(rom, L["symtab"] + 4 * i)
        mod, off = v >> 20, v & 0xFFFFF
        name = cstr(rom, L["names"] + u32(rom, L["nameoffs"] + 4 * i))
        if mod == 0:
            addr, kind = L["text"] + off, "func"
        elif mod in (SEC_RODATA, SEC_DATA):
            addr, kind = L["data"] + off, None
        elif mod == SEC_BSS:
            addr, kind = L["bss"] + off, None
        else:
            continue  # belongs to a runlink module
        if name in seen_names:
            continue
        seen_names.add(name)
        if addr in seen_addrs:
            # an alias; splat wants one name per address
            lines.append("// alias: %s = 0x%08X; (same as %s)" % (name, addr, seen_addrs[addr]))
            continue
        seen_addrs[addr] = name
        if kind == "func" and addr >= L["data"]:
            kind = None
        suffix = " // type:func" if kind == "func" else ""
        lines.append("%s = 0x%08X;%s" % (name, addr, suffix))

    with open(args.out, "w") as f:
        f.write("// generated by tools/runlink_syms.py from the ROM's runlink tables\n")
        f.write("\n".join(lines) + "\n")

    if args.modules:
        nmods = (L["modules"] - L["modtab"]) // 32
        with open(args.modules, "w") as f:
            f.write("# idx rom_start text data bss relocs1 relocs2 init fini\n")
            for m in range(nmods):
                e = struct.unpack_from(">IIIIIHHii", rom, L["modtab"] + 32 * m)
                f.write("%3d 0x%07X 0x%05X 0x%05X 0x%05X 0x%04X 0x%04X %d %d\n" % (
                    m + 1, L["modules"] + e[1], e[2], e[3], e[4], e[5], e[6], e[7], e[8]))

    print("runlink_syms: %d main symbols" % len(seen_addrs))


if __name__ == "__main__":
    main()
